import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { makeElf } from '../support/elf-fixture.js';
import { makeDisc } from '../support/disc-fixture.js';
import { analyzeInput } from '../src/analyzer.js';
import { checkTools } from '../src/ghidra.js';
import { decompileGameCode, codeCoverage } from '../src/game-code.js';
import { exportProject } from '../src/project-export.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tools = await checkTools();
if (!tools.ready) throw new Error('Configure PORT_RE_GHIDRA_DIR e um JDK compatível.');
const working = await mkdtemp(join(process.env.PORT_RE_TEST_DIR || tmpdir(), 'port-re-ghidra-'));
const sourcePath = join(working, 'synthetic.iso'), dir = join(working, 'project');
const original = makeDisc({ extraFiles: { 'HIDDEN.DAT': makeElf({ ppc: true }), 'LOCKED.SELF': Buffer.from('SCE\0' + '0'.repeat(60)), 'TEXT.DAT': Buffer.from('not executable') } });
await writeFile(sourcePath, original);
const report = await analyzeInput({ sourcePath, kind: 'iso', dir, id: randomUUID() });
await decompileGameCode({ report, dir, tools, scriptDir: join(root, 'ghidra_scripts'), maxFunctions: 0, onProgress: p => { if (p.stage === 'scan') console.log(p.message); } });
assert.equal(report.artifacts.length, 3);
for (const artifact of report.artifacts.filter(a => a.decompilable)) {
  const result = artifact.decompilation;
  if (!result) throw new Error(artifact.decompilationFailure?.error || 'Missing export');
  const functions = JSON.parse(await readFile(join(result.exportDir, 'functions.json'), 'utf8'));
  assert.ok(result.decompiled >= 1 && functions.some(f => f.decompiled && f.pseudocode.includes('return')));
  assert.equal(result.requestedLimit, 0);
  assert.equal(result.attempted, result.discovered);
  assert.equal(result.attempted, result.decompiled + result.failed);
  const index = (await readFile(join(result.exportDir, 'functions-index.jsonl'), 'utf8')).trim().split('\n').map(line => JSON.parse(line));
  assert.equal(index.length, result.discovered);
  assert.ok((await readFile(join(result.exportDir, 'disassembly.txt'), 'utf8')).includes('00100000'));
  assert.ok(result.exportedInstructions > 0 && result.definedInstructions >= result.exportedInstructions);
  console.log(JSON.stringify({ target: artifact.architecture, discovered: result.discovered, decompiled: result.decompiled, failed: result.failed, output: result.outputDir }));
}
assert.equal(codeCoverage(report).unsupportedArtifacts, 1);
assert.equal(codeCoverage(report).decompiledFunctions, 2);
const destinationRoot = join(working, 'chosen folder'); await mkdir(destinationRoot);
const exported = await exportProject({ report, projectDir: dir, destinationRoot });
const manifest = JSON.parse(await readFile(join(exported.path, 'manifest.json'), 'utf8'));
assert.equal(manifest.coverage.decompiledFunctions, 2);
assert.ok(manifest.files.some(f => f.path.endsWith('.gpr')));
assert.ok(manifest.files.some(f => f.path.endsWith('functions-index.jsonl')));
assert.deepEqual(await readFile(sourcePath), original);
console.log(`Varredura, Ghidra MIPS/PowerPC e exportação completa verificados: ${exported.path}. Nenhum jogo foi usado.`);
